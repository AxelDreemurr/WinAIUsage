//! Windows 11 widget (Widgets board and lock screen) showing each tool's quota.
//!
//! The app registers as a Windows App SDK widget provider: a COM class (`CLSID`,
//! declared in the package manifest's `windows.comServer` and `com.microsoft.windows.widgets`
//! extensions) that the Widgets host calls when a widget is pinned, shown or resized. The
//! card is an Adaptive Card whose layout switches on `$host.widgetSize`; the lock screen
//! only hosts the `small` size, so that one is kept to a few short lines.
//!
//! Widgets need package identity, so this only runs in the MSIX build. COM calls arrive on
//! RPC threads in the MTA that `start` sets up; usage data is pushed with `publish`.
//!
//! `bindings.rs` is generated by windows-bindgen 0.61 from `Microsoft.Windows.Widgets.winmd`
//! (Windows App Runtime), limited to the provider types used here.

#[allow(clippy::all)]
mod bindings;

use crate::providers::{antigravity::AntigravityData, claude_code::ClaudeCodeData, codex::CodexData};
use crate::AllUsageData;
use bindings::{
    IWidgetProvider, IWidgetProvider_Impl, WidgetActionInvokedArgs, WidgetContext,
    WidgetContextChangedArgs, WidgetManager, WidgetUpdateRequestOptions,
};
use serde_json::{json, Value};
use std::sync::{Mutex, OnceLock};
use windows::Win32::Foundation::{CLASS_E_NOAGGREGATION, E_POINTER};
use windows::Win32::System::Com::{
    CoInitializeEx, CoRegisterClassObject, IClassFactory, IClassFactory_Impl, CLSCTX_LOCAL_SERVER,
    COINIT_MULTITHREADED, REGCLS_MULTIPLEUSE,
};
use windows_core::{implement, IUnknown, Interface, Ref, BOOL, GUID, HSTRING};

/// Must match `com:Class Id` and `CreateInstance ClassId` in the package manifest. When no
/// instance is running, COM starts the app (as a normal tray launch), which registers it.
pub const CLSID: GUID = GUID::from_u128(0xff16c414_3a61_42bf_81e1_e6685d890487);

const REFRESH_VERB: &str = "refresh";
const OPEN_VERB: &str = "open";
const TEMPLATE: &str = include_str!("card.json");

/// Last card data, replayed to widgets the host (re)creates or shows.
static LAST_DATA: Mutex<Option<String>> = Mutex::new(None);
static ACTIONS: OnceLock<Actions> = OnceLock::new();

struct Actions {
    refresh: Box<dyn Fn() + Send + Sync>,
    open: Box<dyn Fn() + Send + Sync>,
}

/// Registers the widget provider. `refresh` / `open` run when the user taps the card's
/// buttons. A no-op without package identity (dev builds).
pub fn start(refresh: impl Fn() + Send + Sync + 'static, open: impl Fn() + Send + Sync + 'static) {
    if !crate::is_packaged() {
        return;
    }
    let _ = ACTIONS.set(Actions {
        refresh: Box::new(refresh),
        open: Box::new(open),
    });
    std::thread::Builder::new()
        .name("widget-provider".into())
        .spawn(|| {
            // SAFETY: plain COM setup on this thread; the registered class object is
            // intentionally kept alive for the life of the process.
            unsafe {
                if CoInitializeEx(None, COINIT_MULTITHREADED).is_err() {
                    return;
                }
                let factory: IClassFactory = Factory.into();
                if CoRegisterClassObject(&CLSID, &factory, CLSCTX_LOCAL_SERVER, REGCLS_MULTIPLEUSE)
                    .is_err()
                {
                    return;
                }
                // Keeps the MTA (and the registration) alive.
                loop {
                    std::thread::park();
                }
            }
        })
        .ok();
}

/// Pushes fresh usage data to every pinned widget.
pub fn publish(data: &AllUsageData) {
    if !crate::is_packaged() {
        return;
    }
    let card = card_data(data, chrono::Local::now()).to_string();
    *LAST_DATA.lock().unwrap() = Some(card.clone());
    // Called from tokio threads: run the WinRT calls on a thread that joins the MTA.
    std::thread::spawn(move || {
        // SAFETY: joins this short-lived thread to the MTA before using WinRT.
        if unsafe { CoInitializeEx(None, COINIT_MULTITHREADED) }.is_err() {
            return;
        }
        let Ok(manager) = WidgetManager::GetDefault() else {
            return;
        };
        if let Ok(ids) = manager.GetWidgetIds() {
            for id in ids.iter() {
                let _ = send(&manager, id, &card);
            }
        }
    });
}

fn send(manager: &WidgetManager, id: &HSTRING, data: &str) -> windows_core::Result<()> {
    let options = WidgetUpdateRequestOptions::CreateInstance(id)?;
    options.SetTemplate(&HSTRING::from(TEMPLATE))?;
    options.SetData(&HSTRING::from(data))?;
    manager.UpdateWidget(&options)
}

fn send_last(id: &HSTRING) -> windows_core::Result<()> {
    let data = LAST_DATA
        .lock()
        .unwrap()
        .clone()
        .unwrap_or_else(|| loading_data().to_string());
    send(&WidgetManager::GetDefault()?, id, &data)
}

// ── COM objects ───────────────────────────────────────────────────────────────

#[implement(IWidgetProvider)]
struct Provider;

impl IWidgetProvider_Impl for Provider_Impl {
    fn CreateWidget(&self, context: Ref<'_, WidgetContext>) -> windows_core::Result<()> {
        send_last(&context.ok()?.Id()?)
    }

    fn DeleteWidget(&self, _id: &HSTRING, _state: &HSTRING) -> windows_core::Result<()> {
        Ok(())
    }

    fn OnActionInvoked(&self, args: Ref<'_, WidgetActionInvokedArgs>) -> windows_core::Result<()> {
        let verb = args.ok()?.Verb()?.to_string();
        if let Some(actions) = ACTIONS.get() {
            match verb.as_str() {
                REFRESH_VERB => (actions.refresh)(),
                OPEN_VERB => (actions.open)(),
                _ => {}
            }
        }
        Ok(())
    }

    fn OnWidgetContextChanged(
        &self,
        args: Ref<'_, WidgetContextChangedArgs>,
    ) -> windows_core::Result<()> {
        // The template adapts to the size itself, but the host expects a fresh update.
        send_last(&args.ok()?.WidgetContext()?.Id()?)
    }

    fn Activate(&self, context: Ref<'_, WidgetContext>) -> windows_core::Result<()> {
        send_last(&context.ok()?.Id()?)
    }

    fn Deactivate(&self, _id: &HSTRING) -> windows_core::Result<()> {
        Ok(())
    }
}

#[implement(IClassFactory)]
struct Factory;

impl IClassFactory_Impl for Factory_Impl {
    fn CreateInstance(
        &self,
        outer: Ref<'_, IUnknown>,
        iid: *const GUID,
        object: *mut *mut core::ffi::c_void,
    ) -> windows_core::Result<()> {
        if object.is_null() || iid.is_null() {
            return Err(E_POINTER.into());
        }
        // SAFETY: COM guarantees `object` / `iid` are valid when non-null (checked above).
        unsafe {
            *object = std::ptr::null_mut();
            if outer.is_some() {
                return Err(CLASS_E_NOAGGREGATION.into());
            }
            let provider: IWidgetProvider = Provider.into();
            provider.query(iid, object).ok()
        }
    }

    fn LockServer(&self, _lock: BOOL) -> windows_core::Result<()> {
        Ok(())
    }
}

// ── Card data ─────────────────────────────────────────────────────────────────

/// One line per tool: its most constrained quota window.
struct Row {
    name: &'static str,
    window: String,
    pct: f64,
    reset: Option<String>,
    cost: Option<f64>,
}

fn card_data(data: &AllUsageData, now: chrono::DateTime<chrono::Local>) -> Value {
    let rows: Vec<Row> = [claude_row(&data.claude_code), codex_row(&data.codex), antigravity_row(&data.antigravity)]
        .into_iter()
        .flatten()
        .collect();

    let rows_json: Vec<Value> = rows
        .iter()
        .map(|r| {
            let pct = r.pct.clamp(0.0, 100.0);
            let mut detail = r.window.clone();
            if let Some(reset) = r.reset.as_deref().and_then(|s| format_reset(s, now)) {
                detail = format!("{detail} · {} {reset}", crate::t("reinicia", "resets"));
            }
            let color = color_for(pct);
            json!({
                "name": r.name,
                "pct": format!("{:.0}%", pct),
                "color": color,
                // Bar = two weighted columns; weights must stay >= 1.
                "used": (pct.round() as u32).max(1),
                "rest": ((100.0 - pct).round() as u32).max(1),
                "barStyle": color.to_ascii_lowercase(),
                "detail": detail,
                "cost": r.cost.filter(|c| *c > 0.0).map(|c| format!("${c:.2} {}", crate::t("hoy", "today"))).unwrap_or_default(),
            })
        })
        .collect();

    json!({
        "title": "WinAIUsage",
        "rows": rows_json,
        "hasRows": !rows.is_empty(),
        "empty": crate::t("Sin datos de uso todavía", "No usage data yet"),
        "updated": format!("{} {}", crate::t("Actualizado", "Updated"), now.format("%H:%M")),
        "refresh": crate::t("Actualizar", "Refresh"),
        "open": crate::t("Abrir", "Open"),
    })
}

fn loading_data() -> Value {
    json!({
        "title": "WinAIUsage",
        "rows": [],
        "hasRows": false,
        "empty": crate::t("Cargando…", "Loading…"),
        "updated": "",
        "refresh": crate::t("Actualizar", "Refresh"),
        "open": crate::t("Abrir", "Open"),
    })
}

fn claude_row(d: &ClaudeCodeData) -> Option<Row> {
    if !d.is_available {
        return None;
    }
    let windows = [
        (crate::t("5 h", "5 h"), d.five_hour.as_ref()),
        (crate::t("Semana", "Week"), d.seven_day.as_ref()),
    ];
    let (label, period) = windows
        .into_iter()
        .filter_map(|(l, p)| Some((l, p?)))
        .max_by(|a, b| a.1.utilization.total_cmp(&b.1.utilization))?;
    Some(Row {
        name: "Claude",
        window: label.to_string(),
        pct: period.utilization,
        reset: Some(period.resets_at.clone()),
        cost: d.today.as_ref().map(|t| t.cost),
    })
}

fn codex_row(d: &CodexData) -> Option<Row> {
    if !d.is_available {
        return None;
    }
    let period = d
        .periods
        .iter()
        .max_by(|a, b| a.utilization.total_cmp(&b.utilization))?;
    let window = match period.label_key.as_str() {
        "codexWeek" => crate::t("Semana", "Week"),
        _ => crate::t("Sesión", "Session"),
    };
    Some(Row {
        name: "Codex",
        window: window.to_string(),
        pct: period.utilization,
        reset: Some(period.resets_at.clone()),
        cost: d.today.as_ref().map(|t| t.cost),
    })
}

fn antigravity_row(d: &AntigravityData) -> Option<Row> {
    if !d.is_available {
        return None;
    }
    let model = d
        .models
        .iter()
        .max_by(|a, b| a.percent_used.total_cmp(&b.percent_used))?;
    Some(Row {
        name: "Antigravity",
        window: model.label.clone(),
        pct: model.percent_used,
        reset: Some(model.reset_time.clone()),
        cost: d.today.as_ref().map(|t| t.cost),
    })
}

/// Adaptive Card text color for a usage percentage.
fn color_for(pct: f64) -> &'static str {
    if pct >= 90.0 {
        "Attention"
    } else if pct >= 70.0 {
        "Warning"
    } else {
        "Good"
    }
}

/// "14:30" today, "mañana 09:00" / "tomorrow 09:00", else "27/11 09:00".
fn format_reset(iso: &str, now: chrono::DateTime<chrono::Local>) -> Option<String> {
    let at = chrono::DateTime::parse_from_rfc3339(iso.trim())
        .ok()?
        .with_timezone(&chrono::Local);
    if at <= now {
        return None;
    }
    let days = (at.date_naive() - now.date_naive()).num_days();
    Some(match days {
        0 => at.format("%H:%M").to_string(),
        1 => format!("{} {}", crate::t("mañana", "tomorrow"), at.format("%H:%M")),
        _ => at.format("%d/%m %H:%M").to_string(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use chrono::TimeZone;

    #[test]
    fn template_is_valid_json() {
        let v: Value = serde_json::from_str(TEMPLATE).unwrap();
        assert_eq!(v["type"], "AdaptiveCard");
    }

    #[test]
    fn formats_resets_relative_to_now() {
        let now = chrono::Local.with_ymd_and_hms(2026, 11, 27, 10, 0, 0).unwrap();
        let at = |h| now + chrono::Duration::hours(h);
        assert_eq!(format_reset(&at(2).to_rfc3339(), now).as_deref(), Some("12:00"));
        assert!(format_reset(&at(24).to_rfc3339(), now).unwrap().ends_with("10:00"));
        assert_eq!(format_reset(&at(-1).to_rfc3339(), now), None);
        assert_eq!(format_reset("", now), None);
    }

    #[test]
    fn colors_by_threshold() {
        assert_eq!(color_for(10.0), "Good");
        assert_eq!(color_for(75.0), "Warning");
        assert_eq!(color_for(95.0), "Attention");
    }
}
